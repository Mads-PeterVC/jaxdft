"""Publish a document's results for other pages of the documentation site.

A validation document calls :func:`publish` once with the chart that best
illustrates its milestone and one or two headline numbers it has computed. The
front page shows them without running any calculation of its own. Results are
written to ``docs/_results/`` (not tracked by git), so they are regenerated by
every render and can never drift from the code.

Not physics; needs the ``docs`` group (altair).
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path

WIDTH = 400
HEIGHT = 240


def results_dir(start: Path | None = None) -> Path:
    """``_results/`` in the Quarto project that contains ``start`` (default: the cwd)."""
    here = Path.cwd() if start is None else Path(start)
    for folder in [here, *here.parents]:
        if (folder / "_quarto.yml").exists():
            out = folder / "_results"
            out.mkdir(exist_ok=True)
            return out
    raise FileNotFoundError(f"no _quarto.yml in {here} or any parent directory")


def publish_numbers(name: str, numbers: dict) -> Path:
    """Write ``numbers`` to ``_results/<name>.json`` and return the path."""
    path = results_dir() / f"{name}.json"
    path.write_text(json.dumps(numbers, ensure_ascii=False, indent=1))
    return path


def publish(
    chart, milestone: str, *, caption: str, headline: Sequence[tuple[str, str]] = ()
) -> Path:
    """Publish ``chart`` as the featured figure of ``milestone``.

    ``chart`` is an altair chart; it is stored resized to the front-page card and
    rendered with the theme enabled at the time of the call. ``headline`` is a
    sequence of ``(label, value)`` pairs with the value already formatted,
    computed by the calling document.
    """
    html = chart.properties(width=WIDTH, height=HEIGHT).to_html(
        fullhtml=False, output_div=f"featured-{milestone}"
    )
    return publish_numbers(
        f"milestone_{milestone}",
        {
            "milestone": milestone,
            "caption": caption,
            "headline": [{"label": label, "value": value} for label, value in headline],
            "html": html,
        },
    )
